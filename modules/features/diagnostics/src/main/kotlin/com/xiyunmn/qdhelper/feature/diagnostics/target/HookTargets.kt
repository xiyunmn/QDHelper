import java.lang.reflect.Modifier

data class HookTargetSpec(
    val id: String,
    val className: String,
    val methodName: String,
    val purpose: String,
    val priority: String = "P0",
    val callProbe: Boolean = true,
    val fallbackMethodNames: List<String> = emptyList(),
    val parameterCount: Int? = null,
    val returnTypeName: String? = null,
    val targetKey: TargetKey.MethodTarget? = null,
    /** Complete public-static shape for exploratory methods without a production TargetKey. */
    val publicStaticParameters: List<String?>? = null,
 ) {
    val methodNames: List<String>
        get() = listOf(methodName) + fallbackMethodNames

    fun matches(method: java.lang.reflect.Method): Boolean {
        val shape = publicStaticParameters
        return (if (shape == null) method.name in methodNames else
            Modifier.isPublic(method.modifiers) && Modifier.isStatic(method.modifiers) &&
                method.parameterTypes.size == shape.size &&
                method.parameterTypes.zip(shape).all { (actual, expected) -> expected == null || actual.name == expected }) &&
            (parameterCount == null || method.parameterTypes.size == parameterCount) &&
            (returnTypeName == null || method.returnType.name == returnTypeName)
    }
}

